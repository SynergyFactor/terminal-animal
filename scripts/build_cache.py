"""Manage the animal caches.

Run with no arguments for an interactive menu, or pass a mode:

  python scripts/build_cache.py --mode missing   add animals from the list that aren't cached yet
  python scripts/build_cache.py --mode stale     re-scrape only entries made by an older parser
  python scripts/build_cache.py --mode update    re-scrape everything in place (old data kept on failure)
  python scripts/build_cache.py --mode rebuild   delete the bundled cache and scrape from scratch
  python scripts/build_cache.py --mode apply     re-apply overrides + fallback databases (offline)
  python scripts/build_cache.py --clear-user     delete the app's local cache of live lookups
  python scripts/build_cache.py --status         show what's cached

Requests are sent one at a time, spaced --delay seconds apart (default 1.0), with automatic
backoff on HTTP 429. Progress is saved every few animals, so an interrupted run can be resumed
with --mode missing.
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app import traits, wiki                   # noqa: E402
from app.cache import encode, load_json, user_cache_path  # noqa: E402

OUT = ROOT / "data" / "animals.json"
LIST = ROOT / "scripts" / "animals.txt"
SAVE_EVERY = 5

MENU = [
    ("missing", "Add missing animals only (fast; keeps everything already cached)"),
    ("stale", "Update outdated entries (scraped by an older version of the parser)"),
    ("update", "Update everything in place (re-scrape all; old data kept if a fetch fails)"),
    ("rebuild", "Delete the bundled cache and rebuild from scratch (old file kept as .bak)"),
    ("apply", "Re-apply overrides and fallback databases to cached animals (offline, instant)"),
    ("fallback", "Download fallback databases and rebuild the trait index"),
    ("clear-user", "Clear the app's local cache of animals looked up live"),
    ("status", "Show cache status"),
    ("skip", "Skip / quit"),
]


# -- helpers -------------------------------------------------------------------------------------
class CacheError(Exception):
    """A problem worth a one-line message rather than a traceback."""


def load(path: Path) -> dict:
    """Cache contents; invalid entries are dropped and a damaged file reads as empty."""
    return load_json(path)


def save(path: Path, data: dict) -> None:
    """Atomic write: a crash or Ctrl+C mid-save never leaves a half-written cache."""
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(".tmp")
        tmp.write_text(json.dumps(data, ensure_ascii=False), "utf-8")
        tmp.replace(path)
    except OSError as e:
        raise CacheError(f"couldn't write {path}: {e}") from e


def read_list(path: Path) -> list[str]:
    try:
        text = path.read_text("utf-8-sig")
    except FileNotFoundError:
        raise CacheError(f"animal list not found: {path}") from None
    except (OSError, ValueError) as e:
        raise CacheError(f"couldn't read animal list {path}: {e}") from e
    names = [" ".join(ln.split())[:300] for ln in text.splitlines()
             if ln.strip() and not ln.lstrip().startswith("#")]
    return list(dict.fromkeys(names))           # drop duplicates, keep order


def attribution_path() -> Path:
    return OUT.with_name("ATTRIBUTION.md")      # next to the cache it describes


def write_attribution(cache: dict, path: Path | None = None) -> None:
    """List the source article and image page for every cached animal (licence compliance)."""
    path = path or attribution_path()
    lines = [
        "# Attribution for data/animals.json",
        "",
        "Generated by `scripts/build_cache.py` — do not edit by hand.",
        "",
        "Text excerpts are from English Wikipedia, licensed under",
        "[CC BY-SA 4.0](https://creativecommons.org/licenses/by-sa/4.0/); follow each article link",
        "for its authors (page history). Images are from Wikipedia / Wikimedia Commons; each file",
        "page lists the author and licence. Taxon data is from Wikidata (CC0). Fallback body-size",
        "data sources are credited in NOTICE.md.",
        "",
        "| Animal | Article | Image |",
        "|---|---|---|",
    ]
    for rec in sorted(cache.values(), key=lambda r: r["title"].lower()):
        title = rec["title"].replace("|", "\\|")
        url = rec.get("url") if wiki.is_wikipedia_url(rec.get("url")) else ""
        img = wiki.image_page_url(rec.get("image_file")) if rec.get("image") else ""
        img_cell = f"[File page]({img})" if img else ("(image page unknown; run --mode stale)"
                                                     if rec.get("image") else "—")
        lines.append(f"| {title} | {f'[Wikipedia]({url})' if url else '—'} | {img_cell} |")
    try:
        path.write_text("\n".join(lines) + "\n", "utf-8")
    except OSError as e:
        print(f"warning: couldn't write {path}: {e}")


def find_key(cache: dict, name: str) -> str | None:
    """Cache key for a list entry (matches the article title or the original query)."""
    n = name.lower()
    if n in cache:
        return n
    return next((k for k, r in cache.items() if r.get("query") == n), None)


is_stale = wiki.is_stale


def diagnose(title: str) -> int:
    """Show step by step what Wikipedia returns for one animal's picture."""
    import json as _json
    print(f"Diagnosing the picture for '{title}' (User-Agent: {wiki.USER_AGENT})")
    data = wiki._get_json(wiki.API, {
        "action": "query", "format": "json", "formatversion": 2, "redirects": 1,
        "prop": "pageimages|info", "piprop": "thumbnail|name", "pithumbsize": wiki.THUMB_WIDTH,
        "inprop": "url", "titles": title})
    pages = (data.get("query") or {}).get("pages") or [{}]
    page = pages[0] if isinstance(pages[0], dict) else {}
    print("1. Page lookup:", _json.dumps({k: page.get(k) for k in ("title", "missing", "pageimage",
                                                                    "thumbnail")}, ensure_ascii=True))
    print("2. Summary-service thumbnail:", wiki._rest_thumbnail(page.get("title") or title) or "(none)")
    image, name, state = wiki.fetch_image(page, page.get("title") or title)
    print("3. Result:", state, f"| file: {name}" if name else "",
          f"| {len(image):,} bytes, {wiki._image_kind(image)}" if image else "")
    return 0 if state in ("ok", "none_on_wikipedia") else 1


def status() -> None:
    names = read_list(LIST)
    cache = load(OUT)
    have = [n for n in names if find_key(cache, n)]
    stale = [n for n in have if is_stale(cache[find_key(cache, n)])]
    no_mass = [r["title"] for r in cache.values() if not r.get("mass_kg")]
    no_image: dict[str, int] = {}
    for r in cache.values():
        if not r.get("image"):
            k = str(r.get("image_status") or "unknown (older version)").split(":")[0]
            no_image[k] = no_image.get(k, 0) + 1
    origins: dict[str, int] = {}
    for r in cache.values():
        o = (r.get("mass_origin") or "unknown").split(" (")[0]
        origins[o] = origins.get(o, 0) + 1
    user = load(user_cache_path())
    print(f"Bundled cache: {OUT}")
    print(f"  {len(cache)} entries; {len(have)}/{len(names)} of the list cached, "
          f"{len(names) - len(have)} missing, {len(stale)} outdated or with a failed image download.")
    if origins:
        print("  Mass came from: " + ", ".join(f"{k} {v}" for k, v in sorted(origins.items(), key=lambda x: -x[1])))
    if no_image:
        print(f"  Without a picture: {sum(no_image.values())} (" +
              ", ".join(f"{k} {v}" for k, v in no_image.items()) + ")  -> --mode stale retries them")
    if no_mass:
        print(f"  No mass in any source: {', '.join(sorted(no_mass))}  (add them to data/overrides.csv)")
    idx = traits.index()
    print(f"Fallback index: {len(idx['species']):,} species" if idx["species"]
          else "Fallback index: not built (run the 'fallback' option)")
    print(f"User cache:    {user_cache_path()}\n  {len(user)} entries")


def clear_user() -> None:
    path = user_cache_path()
    try:
        if path.exists():
            path.unlink()
            print(f"Deleted user cache {path}")
        else:
            print("User cache is already empty.")
    except OSError as e:
        raise CacheError(f"couldn't delete {path}: {e}") from e


# -- scraping ------------------------------------------------------------------------------------
def apply_fallbacks() -> int:
    traits.reload()
    cache = load(OUT)
    changed = 0
    for rec in cache.values():
        before = (rec.get("mass_kg"), rec.get("length_m"), rec.get("mass_origin"))
        traits.enrich(rec)
        after = (rec.get("mass_kg"), rec.get("length_m"), rec.get("mass_origin"))
        if before != after:
            changed += 1
            m = f"{rec['mass_kg']:.4g} kg" if rec.get("mass_kg") else "no mass"
            print(f"  {rec['title']:<28} {m:<14} from {rec.get('mass_origin') or '—'}")
    save(OUT, cache)
    write_attribution(cache)
    missing = [r["title"] for r in cache.values() if not r.get("mass_kg")]
    print(f"\nUpdated {changed} of {len(cache)} animals.")
    if missing:
        print("Still no mass:", ", ".join(sorted(missing)))
    return 0


def run_fallback(args: list[str]) -> int:
    sys.path.insert(0, str(ROOT / "scripts"))
    import fallback_data
    code = fallback_data.main(args)
    traits.reload()
    return code


def scrape(mode: str, delay: float) -> int:
    wiki.set_request_interval(delay)
    names = read_list(LIST)
    if not traits.index()["species"]:
        print("Note: fallback index not built; gaps will only be filled from Wikidata. "
              "Run --mode fallback first for full coverage.")

    if mode == "rebuild":
        if OUT.exists():
            shutil.copy2(OUT, OUT.with_suffix(".json.bak"))
            print(f"Backed up old cache to {OUT.with_suffix('.json.bak').name}")
        cache: dict = {}
        save(OUT, cache)
    else:
        cache = load(OUT)

    if mode in ("missing", "rebuild"):
        todo = [n for n in names if not find_key(cache, n)]
    elif mode == "stale":
        todo = [n for n in names if not find_key(cache, n) or is_stale(cache[find_key(cache, n)])]
    else:  # update
        todo = list(names)

    est = len(todo) * 2 * delay
    print(f"Mode '{mode}': {len(todo)} of {len(names)} animals to scrape "
          f"(~{est / 60:.1f} min at one request per {delay:g}s).")
    if not todo:
        return 0

    failed: list[str] = []
    done = 0

    def attempt(names_: list[str]) -> list[str]:
        nonlocal done
        missed = []
        for i, name in enumerate(names_, 1):
            try:
                rec = wiki.fetch_animal(name)
            except Exception as e:  # noqa: BLE001
                print(f"  [{i}/{len(names_)}] {name:<28} FAILED: {e}")
                missed.append(name)
                continue
            old_key = find_key(cache, name)
            old = cache.get(old_key) if old_key else None
            if rec["image_failed"] and old and old.get("image"):
                rec["image"] = old["image"]          # keep the old picture rather than lose it
                rec["image_failed"] = False
            if old_key and old_key != rec["title"].lower():
                cache.pop(old_key, None)
            rec["query"] = name.lower()
            cache[rec["title"].lower()] = encode(rec)
            done += 1
            mass = f"{rec['mass_kg']:.4g} kg" if rec["mass_kg"] else "no mass found"
            origin = f"  [{rec.get('mass_origin')}]" if rec.get("mass_origin") not in (None, "", "Wikipedia") else ""
            img = "" if rec["image"] else f"  (no image: {rec.get('image_status', '?')})"
            print(f"  [{i}/{len(names_)}] {rec['title']:<28} {mass}{origin}{img}", flush=True)
            if rec["image_failed"]:
                missed.append(name)
            if done % SAVE_EVERY == 0:
                save(OUT, cache)
        save(OUT, cache)
        return missed

    try:
        failed = attempt(todo)
        if failed:
            wait = 30
            print(f"\n{len(failed)} incomplete. Waiting {wait}s, then retrying them more slowly…")
            time.sleep(wait)
            wiki.set_request_interval(delay * 2)
            failed = attempt(failed)
    except KeyboardInterrupt:
        save(OUT, cache)
        write_attribution(cache)
        print("\nInterrupted. Progress saved; run again with --mode missing (or stale) to resume.")
        return 130

    size_kb = OUT.stat().st_size / 1024
    write_attribution(cache)
    print(f"\nSaved {len(cache)} animals to {OUT} ({size_kb:.0f} KB); attribution in {attribution_path().name}.")
    if failed:
        print("Still incomplete (cached data kept where it existed):", ", ".join(failed))
        print("Re-run with --mode stale later to fill these in.")
        return 1
    return 0


# -- entry ---------------------------------------------------------------------------------------
def menu() -> str:
    print("\nTerminal Velocity — cache manager\n")
    for i, (_, label) in enumerate(MENU, 1):
        print(f"  {i}) {label}")
    while True:
        choice = input(f"\nChoose 1-{len(MENU)} [1]: ").strip() or "1"
        if choice.isdigit() and 1 <= int(choice) <= len(MENU):
            return MENU[int(choice) - 1][0]
        print("Please enter a number from the list.")


def main(argv: list[str] | None = None) -> int:
    try:
        return _main(argv)
    except CacheError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    except (KeyboardInterrupt, EOFError):
        print("\nStopped.")
        return 130


def _main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--mode", choices=["missing", "stale", "update", "rebuild", "apply", "fallback", "skip"])
    ap.add_argument("--clear-user", action="store_true", help="delete the app's local lookup cache")
    ap.add_argument("--status", action="store_true")
    ap.add_argument("--diagnose", metavar="TITLE", help="show what Wikipedia returns for one animal's picture")
    ap.add_argument("--delay", type=float, default=1.0,
                    help="seconds between requests (default 1.0; raise it if you still see 429s)")
    ap.add_argument("--list", type=Path, help="alternative animal list file")
    ap.add_argument("-y", "--yes", action="store_true", help="don't ask for confirmation")
    args = ap.parse_args(argv)
    global LIST
    if args.list:
        LIST = args.list

    if args.diagnose:
        return diagnose(args.diagnose)
    if args.status:
        status()
    if args.clear_user:
        clear_user()
    mode = args.mode
    if mode is None and not (args.status or args.clear_user):
        if not sys.stdin.isatty():
            mode = "missing"
        else:
            while True:
                mode = menu()
                if mode == "status":
                    status()
                elif mode == "clear-user":
                    clear_user()
                else:
                    break
    if mode in (None, "skip"):
        return 0
    if mode == "apply":
        return apply_fallbacks()
    if mode == "fallback":
        return run_fallback([])
    if mode == "rebuild" and not args.yes and sys.stdin.isatty():
        if input("This deletes the bundled cache (a .bak copy is kept). Continue? [y/N]: ").strip().lower() != "y":
            print("Cancelled.")
            return 0
    return scrape(mode, min(max(args.delay, 0.2), 60.0))


if __name__ == "__main__":
    sys.exit(main())
